//! Choosing a skeleton and placing it on the imported mesh.
//!
//! # Boundary
//!
//! This is projection, not algorithm (`memory/architecture.md` §2). The fitting
//! lives in `m2m_rig::fit`; what happens here is turning a `glb::Document` into
//! the plain inputs that crate takes. `m2m-rig` deliberately does **not** depend
//! on `m2m-io` — the rigging maths has no business knowing about file formats —
//! so somebody has to bridge the two, and the adapter is the right somebody.

use m2m_rig::fit::{Fitted, RestPose};
use serde::{Deserialize, Serialize};

/// A user-placed rig marker. Re-exported so the app can name it as `rig::Marker`
/// without depending on `m2m-rig` directly.
pub use m2m_rig::fit::Marker;

// Generated by `build.rs`: every rig `.glb`, by file name.
include!(concat!(env!("OUT_DIR"), "/skeletons.rs"));

/// A creature template offered in the Choose Skeleton step.
#[derive(Debug, Serialize)]
pub struct SkeletonTemplate {
    /// The template's name, e.g. `human`.
    pub name: String,
    /// How many bones its skeleton has.
    pub bones: usize,
    /// Chain names, so the UI can say what the rig actually covers.
    pub chains: Vec<String>,
    /// Whether the rig for it is available to fit.
    ///
    /// A manifest naming a `.glb` that is not embedded would otherwise fail
    /// only when the user picked it.
    pub available: bool,
    /// A creature-specific tip for placing this skeleton (design.md §7).
    pub guidance: String,
}

/// A template skeleton placed on a mesh, ready to draw.
///
/// Deserialisable as well as serialisable: it goes out to the frontend to be
/// drawn and comes back to be bound, which is what will let a user's manual
/// adjustments reach the solver once the gizmo exists.
#[derive(Debug, Serialize, Deserialize, PartialEq)]
pub struct FittedSkeleton {
    /// Bone names.
    pub bones: Vec<String>,
    /// Each bone's parent, as an index into `bones`. `None` for a root.
    ///
    /// Carried because a skeleton is drawn as segments between a bone and its
    /// parent, and [`Fitted`] is only names and positions — the hierarchy lives
    /// in the rig file's node graph.
    pub parents: Vec<Option<usize>>,
    /// World-space position of each bone, in metres.
    pub positions: Vec<[f32; 3]>,
    /// Each bone's **local rest rotation**, xyzw, taken from the template.
    ///
    /// Fitting moves joints; it does not turn them, so these come through from
    /// the rig the template names rather than from the fit. Measured: all 66
    /// bones of `rig-human.glb` carry one, up to 179.94 degrees. Dropping them
    /// costs bone roll — which artists notice — and puts every clip authored
    /// against the template out of alignment, because the clip's rest pose and
    /// the exported rig's would no longer agree.
    pub rotations: Vec<[f32; 4]>,
    /// The uniform scale the template was fitted with, reported so a wildly
    /// wrong pick is visible as a number and not only as a shape.
    pub scale: f32,
    /// The arm pose detected from where the arms landed — `"t-pose"`,
    /// `"a-pose"`, `"arms-down"` or `"other"`. `"other"` for a non-human
    /// template, whose arms these bone names do not describe. The UI reports it
    /// rather than the app silently assuming a pose (P3-P2).
    pub pose: String,
}

/// Errors the skeleton step can produce.
#[derive(Debug, thiserror::Error)]
pub enum RigError {
    /// The shipped manifests did not parse.
    #[error("template manifests: {0}")]
    Manifests(#[from] serde_json::Error),
    /// No template by that name ships.
    #[error("no template named {0}")]
    UnknownTemplate(String),
    /// The template names a rig file that is not embedded.
    #[error("template {template} needs {skeleton}, which is not bundled")]
    MissingSkeleton {
        /// The template that asked.
        template: String,
        /// The file it named.
        skeleton: String,
    },
    /// A rig file could not be read.
    #[error(transparent)]
    Read(#[from] m2m_io::glb::GlbError),
    /// The model the user imported could not be read.
    #[error(transparent)]
    Import(#[from] m2m_io::import::ImportError),
    /// The rig carries no skin, so there is no joint list to fit.
    #[error("{0} has no skin, so it names no bones")]
    NoSkin(String),
    /// There was nothing to bind, or nothing to bind it to.
    #[error("cannot bind: {reason}")]
    NothingToBind {
        /// What was missing.
        reason: &'static str,
    },
    /// A bone's parent appears after it, which `fbx::build` cannot express.
    #[error("bone {bone} has parent {parent}, which comes after it")]
    BadBoneOrder {
        /// The bone whose parent is out of order.
        bone: usize,
        /// The parent that comes too late.
        parent: usize,
    },
    /// Writing the FBX failed.
    #[error(transparent)]
    Fbx(#[from] m2m_io::fbx::FbxError),
    /// The library has no clip by that name.
    #[error("no clip named {0}")]
    UnknownClip(String),
    /// The fitting pipeline could not place the skeleton.
    #[error("cannot fit {template}: the mesh or the template has nothing to work with")]
    CannotFit {
        /// The template that was being fitted.
        template: String,
    },
}

/// Every template that ships, with whether its rig is actually bundled.
pub fn templates() -> Result<Vec<SkeletonTemplate>, RigError> {
    Ok(m2m_rig::template::all()?
        .into_iter()
        .map(|template| SkeletonTemplate {
            bones: template.bones().count(),
            chains: template.chains.iter().map(|c| c.name.clone()).collect(),
            available: skeleton_bytes(&template.skeleton).is_some(),
            guidance: template.guidance,
            name: template.name,
        })
        .collect())
}

/// The bytes of an embedded rig, by the file name a manifest gives.
fn skeleton_bytes(name: &str) -> Option<&'static [u8]> {
    SKELETONS
        .iter()
        .find(|(embedded, _)| *embedded == name)
        .map(|(_, bytes)| *bytes)
}

/// Places a named template's skeleton on a model.
///
/// # Errors
///
/// [`RigError`] for an unknown template, a rig that is not bundled, a file that
/// will not read, or a mesh the pipeline cannot place a skeleton on.
pub fn fit(template_name: &str, model: &[u8]) -> Result<FittedSkeleton, RigError> {
    let template = m2m_rig::template::all()?
        .into_iter()
        .find(|t| t.name == template_name)
        .ok_or_else(|| RigError::UnknownTemplate(template_name.to_owned()))?;

    let rig_bytes =
        skeleton_bytes(&template.skeleton).ok_or_else(|| RigError::MissingSkeleton {
            template: template.name.clone(),
            skeleton: template.skeleton.clone(),
        })?;

    let rig = m2m_io::glb::read(rig_bytes)?;
    let TemplateRest {
        rest,
        parents,
        rotations: rest_rotations,
    } = rest_pose(&rig, &template.skeleton)?;
    let mesh = mesh_of(&m2m_io::import::load(model)?);

    // 128 is the resolution the fitting tests use across all nine creatures.
    let fitted: Fitted =
        m2m_rig::fit::fit_template(&template, &rest, &mesh, 128).ok_or(RigError::CannotFit {
            template: template.name.clone(),
        })?;

    Ok(fitted_to_skeleton(
        &template,
        &rest,
        &parents,
        rest_rotations,
        fitted,
    ))
}

/// Fits a named template's skeleton to user-placed markers.
///
/// The marker-placement flow: the markers pin the key joints, and the **mesh**
/// places what they don't — chiefly standing the feet on the ground (see
/// [`m2m_rig::fit::fit_from_markers`] and `docs/research/marker-skeleton-solving.md`).
///
/// # Errors
///
/// [`RigError`] for an unknown template, a rig that is not bundled or will not
/// read, a model that will not read, or markers that name fewer than two of the
/// template's bones.
pub fn fit_from_markers(
    template_name: &str,
    markers: &[m2m_rig::fit::Marker],
    model: &[u8],
) -> Result<FittedSkeleton, RigError> {
    let template = m2m_rig::template::all()?
        .into_iter()
        .find(|t| t.name == template_name)
        .ok_or_else(|| RigError::UnknownTemplate(template_name.to_owned()))?;

    let rig_bytes =
        skeleton_bytes(&template.skeleton).ok_or_else(|| RigError::MissingSkeleton {
            template: template.name.clone(),
            skeleton: template.skeleton.clone(),
        })?;
    let rig = m2m_io::glb::read(rig_bytes)?;
    let TemplateRest {
        rest,
        parents,
        rotations: rest_rotations,
    } = rest_pose(&rig, &template.skeleton)?;
    let mesh = mesh_of(&m2m_io::import::load(model)?);

    let fitted = m2m_rig::fit::fit_from_markers(&template, &rest, &parents, markers, Some(&mesh))
        .ok_or(RigError::CannotFit {
        template: template.name.clone(),
    })?;

    Ok(fitted_to_skeleton(
        &template,
        &rest,
        &parents,
        rest_rotations,
        fitted,
    ))
}

/// Turns a placed [`Fitted`] skeleton into the [`FittedSkeleton`] the app uses:
/// reorients the rest rotations onto where the limbs actually landed and labels
/// the pose. Shared by every fitting entry point so they cannot drift.
fn fitted_to_skeleton(
    template: &m2m_rig::template::Template,
    rest: &RestPose,
    parents: &[Option<usize>],
    rest_rotations: Vec<[f32; 4]>,
    fitted: Fitted,
) -> FittedSkeleton {
    // Paired by NAME, not position: `Fitted` is built from the rest pose and
    // keeps its order today, but nothing in either type says it must.
    let rotation_of: std::collections::HashMap<&str, [f32; 4]> = rest
        .bones
        .iter()
        .map(String::as_str)
        .zip(rest_rotations)
        .collect();
    // The template's rest data, in the fitted skeleton's bone order.
    let template_local: Vec<glam::Quat> = fitted
        .bones
        .iter()
        .map(|bone| {
            glam::Quat::from_array(
                rotation_of
                    .get(bone.as_str())
                    .copied()
                    .unwrap_or([0.0, 0.0, 0.0, 1.0]),
            )
        })
        .collect();
    let template_positions: Vec<glam::Vec3> = fitted
        .bones
        .iter()
        .map(|bone| rest.position_of(bone).unwrap_or(glam::Vec3::ZERO))
        .collect();

    // Reorient the rest rotations to match where the arms actually landed, so a
    // template fitted onto a mismatched pose (T-pose rig, A-pose mesh) exports
    // and retargets correctly instead of turning the arms around the template's
    // axis (P3-P3). A fit that already agrees with its template is unchanged.
    let aim = m2m_rig::orient::limb_aims(template, &fitted.bones);
    let rotations: Vec<[f32; 4]> = m2m_rig::orient::pose_matched_local_rotations(
        parents,
        &template_positions,
        &template_local,
        &fitted.positions,
        &aim,
    )
    .iter()
    .map(glam::Quat::to_array)
    .collect();

    // The mesh's own up is +Y; the fitted arms drop from horizontal by pose.
    let pose = m2m_rig::pose::pose_of_fitted(&fitted, glam::Vec3::Y)
        .label()
        .to_owned();

    FittedSkeleton {
        parents: parents.to_vec(),
        positions: fitted.positions.iter().map(|p| p.to_array()).collect(),
        rotations,
        scale: fitted.scale,
        bones: fitted.bones,
        pose,
    }
}

/// What binding produced, without the weights themselves.
///
/// The weights are `vertices x 4` indices and `vertices x 4` floats — about
/// 600 KB for the reference character — so they belong on the bulk channel
/// beside the geometry, not in a JSON reply. Until something draws them, what
/// crosses is the part a person can act on: whether every vertex is attached,
/// and where the solver had to guess.
#[derive(Debug, Serialize, PartialEq)]
pub struct BindReport {
    /// Vertices in the mesh that was bound.
    pub vertices: usize,
    /// Bones allowed to receive weight.
    pub weighted_bones: usize,
    /// Bones excluded because they are the root or a leaf.
    pub excluded_bones: usize,
    /// Vertices no bone reached through the mesh, which fell back to the
    /// nearest bone in a straight line.
    ///
    /// Non-zero means part of the model is a disconnected island — a loose
    /// accessory, or a limb modelled apart from the body. Reported because the
    /// deformation there is a guess, and a guess the user can see is one they
    /// can fix.
    pub fallback_vertices: usize,
    /// How many vertices have 1, 2, 3 or 4 influences.
    pub influence_histogram: [usize; 4],
    /// Vertices with no influence at all.
    ///
    /// Counted separately rather than folded into the histogram's first bucket:
    /// an unweighted vertex is not a lightly-weighted one, it is a vertex that
    /// detaches when the rig moves, and the two must never look alike.
    ///
    /// **This is a canary across a crate boundary, and no test can make it
    /// fire.** `m2m_core::skinning::assign_weights` always writes at least one
    /// influence — a vertex no bone reached takes the straight-line fallback at
    /// weight 1.0 — so nothing that can be fed in produces a non-zero here. A
    /// mutation folding this back into the histogram therefore survives, by
    /// construction rather than for want of a fixture. It stays because the
    /// invariant belongs to another crate and this costs one counter.
    pub unweighted_vertices: usize,
}

/// Binds a mesh to a fitted skeleton.
///
/// # Bone segments
///
/// A bone runs from its own joint **towards its first child**, which is what
/// "the bone" means to anyone looking at it: vertices near the upper arm should
/// follow `upperarm`. The tempting alternative — a segment from the parent's
/// joint down to this one — is off by one, and would weight the shoulder to the
/// upper arm. A branching joint such as the hips has no single continuation and
/// takes its first child in joint order; a leaf bone's segment is a point,
/// which costs nothing because leaves are excluded from weighting anyway.
///
/// # The bone mask
///
/// The root and every leaf are excluded, which is the legacy invariant
/// `m2m_core::skinning::BoneMask` documents: the root carries global transform
/// only, and a leaf exists to orient its parent.
///
/// # Errors
///
/// [`RigError`] for a model that will not read, a mesh that cannot be
/// voxelised, or a skeleton with nothing that may hold weight.
pub fn bind(model: &[u8], skeleton: &FittedSkeleton, falloff: f32) -> Result<BindReport, RigError> {
    Ok(solve(model, skeleton, falloff)?.2)
}

/// The solve behind [`bind`] and [`export_glb`]: mesh, weights and report.
///
/// Export recomputes rather than carrying the weights out to the frontend and
/// back — they are about 600 KB, and the whole solve takes ~56 ms on the
/// reference body. A round trip through the webview would cost more than doing
/// it twice, and there would be a cache to invalidate every time a bone moved.
fn solve(
    model: &[u8],
    skeleton: &FittedSkeleton,
    falloff: f32,
) -> Result<
    (
        m2m_core::mesh::Mesh,
        m2m_core::skinning::SkinWeights,
        BindReport,
    ),
    RigError,
> {
    let mesh = mesh_of(&m2m_io::import::load(model)?);
    if mesh.positions.is_empty() {
        return Err(RigError::NothingToBind {
            reason: "the model has no vertices",
        });
    }

    let mut has_child = vec![false; skeleton.bones.len()];
    for parent in skeleton.parents.iter().flatten() {
        if let Some(slot) = has_child.get_mut(*parent) {
            *slot = true;
        }
    }

    let segments = bone_segments(skeleton);

    // A bone that is neither the root nor a leaf may hold weight.
    let allowed: Vec<bool> = (0..skeleton.bones.len())
        .map(|bone| skeleton.parents.get(bone).copied().flatten().is_some() && has_child[bone])
        .collect();
    let weighted_bones = allowed.iter().filter(|a| **a).count();
    if weighted_bones == 0 {
        return Err(RigError::NothingToBind {
            reason: "every bone is either the root or a leaf",
        });
    }

    let grid = m2m_core::voxel::VoxelGrid::build(&mesh, 128).ok_or(RigError::NothingToBind {
        reason: "the mesh could not be voxelised",
    })?;
    let field = m2m_core::geodesic::GeodesicField::compute(&mesh, &grid, &segments).ok_or(
        RigError::NothingToBind {
            reason: "no bone could reach the mesh",
        },
    )?;

    let weights = m2m_core::skinning::assign_weights(
        &field,
        &mesh.positions,
        &segments,
        &allowed,
        m2m_core::skinning::SkinningParams::new(falloff),
    );

    let mut influence_histogram = [0usize; 4];
    let mut unweighted_vertices = 0usize;
    for vertex in 0..weights.vertex_count() {
        match weights.influences(vertex).count() {
            0 => unweighted_vertices += 1,
            count => {
                if let Some(slot) = influence_histogram.get_mut(count - 1) {
                    *slot += 1;
                }
            }
        }
    }

    let report = BindReport {
        vertices: mesh.positions.len(),
        weighted_bones,
        excluded_bones: skeleton.bones.len() - weighted_bones,
        fallback_vertices: weights.fallback_vertices.len(),
        influence_histogram,
        unweighted_vertices,
    };
    Ok((mesh, weights, report))
}

/// Writes the rigged model as a `.glb`: mesh, skeleton and skin weights.
///
/// # What the exported file is
///
/// The mesh in world space, one node per bone at its fitted position, and a
/// skin binding them. Bone rotations are identity: a fitted skeleton is a set
/// of joint **positions**, and inventing orientations for it would be making up
/// data the fitter never produced. A joint's position is what deforms the mesh,
/// so the export is complete for skinning even though a bone roll is not
/// recovered.
///
/// Inverse bind matrices are the inverse of each bone's world translation,
/// which is exact here because the mesh node carries the identity: the mesh
/// positions are already in world space, so `jointWorld * IBM` is the identity
/// at bind and the mesh does not move until a bone does.
///
/// # Errors
///
/// Whatever the solve produces, plus a write failure from `glb::write`.
/// A per-vertex RGBA weight-paint overlay, four floats per vertex.
///
/// Two things a person needs to see after binding, in one image:
///
/// - **Which bone owns each vertex** — coloured by the vertex's dominant
///   influence, a stable hue per bone index, so the weight regions are visible
///   and a vertex assigned to the wrong bone stands out as a wrong-coloured
///   patch.
/// - **Where the solver guessed** — a vertex the geodesic field could not reach
///   through the mesh took a straight-line fallback, and those are painted a
///   flat flag colour rather than a bone hue. These are the regions to check by
///   hand; `bind` counts them, this shows *where* they are.
///
/// The hue comes from the bone index by the golden-ratio walk of the colour
/// wheel, which keeps adjacent bones far apart in hue without a palette to
/// maintain.
fn weight_colors(weights: &m2m_core::skinning::SkinWeights) -> Vec<f32> {
    // Fallback vertices are a red flag, literally.
    const FLAG: [f32; 4] = [1.0, 0.15, 0.15, 1.0];
    let flagged: std::collections::HashSet<u32> =
        weights.fallback_vertices.iter().copied().collect();

    let mut colors = Vec::with_capacity(weights.vertex_count() * 4);
    for vertex in 0..weights.vertex_count() {
        if flagged.contains(&(vertex as u32)) {
            colors.extend_from_slice(&FLAG);
            continue;
        }
        // The dominant influence: the bone with the greatest weight.
        let dominant = weights
            .influences(vertex)
            .max_by(|a, b| a.1.total_cmp(&b.1))
            .map_or(0, |(bone, _)| bone);
        let [r, g, b] = bone_hue(dominant);
        colors.extend_from_slice(&[r, g, b, 1.0]);
    }
    colors
}

/// A stable, well-spread RGB colour for a bone index.
///
/// The hue advances by the golden angle (0.618 of the wheel) per bone, so
/// consecutive bones — which are usually neighbours in the body — never share a
/// hue, and no palette has to be kept in step with the bone count.
fn bone_hue(bone: u16) -> [f32; 3] {
    let hue = (f32::from(bone) * 0.618_034) % 1.0;
    // HSV to RGB at full saturation and value.
    let h = hue * 6.0;
    let x = 1.0 - (h % 2.0 - 1.0).abs();
    let (r, g, b) = match h as u32 {
        0 => (1.0, x, 0.0),
        1 => (x, 1.0, 0.0),
        2 => (0.0, 1.0, x),
        3 => (0.0, x, 1.0),
        4 => (x, 0.0, 1.0),
        _ => (1.0, 0.0, x),
    };
    [r, g, b]
}

/// Assembles the rigged model into a glTF document: one node per bone, the mesh
/// on a skinned node, plus optional per-vertex `colors` and animation `clips`.
///
/// The exports and the weight-paint overlay all funnel through here, so a bone's
/// placement, its inverse bind matrix and the bind pose are defined once. The
/// mesh's own node carries the skin and the identity transform, which glTF
/// ignores for a skinned node.
fn rigged_document(
    skeleton: &FittedSkeleton,
    mesh: &m2m_core::mesh::Mesh,
    weights: &m2m_core::skinning::SkinWeights,
    colors: Vec<f32>,
    shading: FbxShading,
    clips: Vec<m2m_io::glb::Clip>,
) -> m2m_io::glb::Document {
    let position = |index: usize| {
        skeleton
            .positions
            .get(index)
            .map_or(glam::Vec3::ZERO, |p| glam::Vec3::from(*p))
    };
    let world_rotation = world_rotations(skeleton);

    // One node per bone. A child's local translation is expressed in its
    // PARENT'S rotated frame, so the composed world lands back on the fitted
    // position — the raw world offset would only work if every bone sat
    // unrotated, which none do.
    let mut nodes: Vec<m2m_io::glb::Node> = skeleton
        .bones
        .iter()
        .enumerate()
        .map(|(bone, name)| {
            let parent = skeleton.parents.get(bone).copied().flatten();
            let offset = position(bone) - parent.map_or(glam::Vec3::ZERO, position);
            let local = match parent {
                Some(parent) => world_rotation[parent].inverse() * offset,
                None => offset,
            };
            m2m_io::glb::Node {
                name: name.clone(),
                parent,
                transform: m2m_io::glb::Trs {
                    translation: local.to_array(),
                    rotation: skeleton
                        .rotations
                        .get(bone)
                        .copied()
                        .unwrap_or([0.0, 0.0, 0.0, 1.0]),
                    scale: [1.0, 1.0, 1.0],
                },
                skin: None,
            }
        })
        .collect();

    // "Without Skin": no mesh geometry, so the export is skeleton + animation
    // only (the bone nodes above plus `clips`). Skip the mesh node, primitive,
    // skin and material entirely.
    let has_mesh = !mesh.positions.is_empty();

    // The source material, as a glb material (the mime comes from the file name
    // the shading reader assigned). Empty for the weight overlay.
    let materials: Vec<m2m_io::glb::Material> = shading
        .material
        .as_ref()
        .map(|m| m2m_io::glb::Material {
            base_color_factor: [
                m.diffuse[0] as f32,
                m.diffuse[1] as f32,
                m.diffuse[2] as f32,
                1.0,
            ],
            base_color_image: m.image.as_ref().map(|(bytes, name)| m2m_io::glb::Image {
                data: bytes.clone(),
                mime: if name.ends_with("png") {
                    "image/png".into()
                } else {
                    "image/jpeg".into()
                },
            }),
        })
        .into_iter()
        .collect();
    let material = (!materials.is_empty()).then_some(0);

    let (primitives, skins) = if has_mesh {
        let inverse_bind_matrices = (0..skeleton.bones.len())
            .map(|bone| {
                glam::Mat4::from_rotation_translation(world_rotation[bone], position(bone))
                    .inverse()
                    .to_cols_array()
            })
            .collect();
        let mesh_node = nodes.len();
        nodes.push(m2m_io::glb::Node {
            name: "mesh".into(),
            parent: None,
            transform: m2m_io::glb::Trs {
                translation: [0.0, 0.0, 0.0],
                rotation: [0.0, 0.0, 0.0, 1.0],
                scale: [1.0, 1.0, 1.0],
            },
            skin: Some(0),
        });
        (
            vec![m2m_io::glb::Primitive {
                mesh: 0,
                node: Some(mesh_node),
                positions: mesh.positions.iter().flat_map(|p| p.to_array()).collect(),
                // The weight overlay passes empty shading; an FBX-source export
                // passes the source's normals, UVs and material (aligned to this
                // merged mesh), so the rebuilt glb keeps all of them.
                normals: shading.normals,
                uvs: shading.uvs,
                material,
                indices: mesh.indices.clone(),
                joints: weights.indices.clone(),
                weights: weights.weights.clone(),
                colors,
            }],
            vec![m2m_io::glb::Skin {
                joints: (0..skeleton.bones.len()).collect(),
                inverse_bind_matrices,
            }],
        )
    } else {
        (Vec::new(), Vec::new())
    };

    m2m_io::glb::Document {
        primitives,
        materials,
        skins,
        nodes,
        clips,
        report: m2m_io::glb::GlbReport::default(),
    }
}

/// Writes the bound model with a weight-paint overlay baked into vertex colours.
///
/// Shares [`solve`] with the exports, so the overlay always shows the weights
/// the export would write — the same one solve, three destinations now.
///
/// # Errors
///
/// Whatever the solve produces, plus a `glb::write` failure.
pub fn overlay_glb(
    model: &[u8],
    skeleton: &FittedSkeleton,
    falloff: f32,
) -> Result<Vec<u8>, RigError> {
    check_bone_order(skeleton)?;
    let (mesh, weights, _) = solve(model, skeleton, falloff)?;
    let colors = weight_colors(&weights);
    let document = rigged_document(
        skeleton,
        &mesh,
        &weights,
        colors,
        FbxShading::default(),
        Vec::new(),
    );
    Ok(m2m_io::glb::write(&document)?)
}

/// Writes the rigged model as a `.glb`, preserving the source's materials,
/// textures, UVs and normals.
///
/// When the source is itself a glTF (`.glb`), the rig is **grafted onto the
/// original file** — the skin, a skeleton of nodes and any animation are added
/// and nothing else is touched, so materials, textures, UVs and normals survive
/// by construction (see [`m2m_io::glb::graft`]). An FBX source has no glTF to
/// keep, so it is rebuilt: it keeps the normals and UVs the reader carried
/// through, but takes the default material (FBX materials/textures are not read
/// yet).
/// An animation to bake into an export: a library, the clip in it, and options.
#[derive(Debug, Clone, Copy)]
pub struct Animation<'a> {
    /// The animation-library `.glb` bytes.
    pub library: &'a [u8],
    /// The clip name to retarget from the library.
    pub clip: &'a str,
    /// Mirror the motion left↔right across the sagittal plane.
    pub mirror: bool,
    /// Character Arm-Space: 0–100, 50 neutral. Below 50 narrows the arms toward
    /// the body, above 50 widens them.
    pub arm_space: f32,
    /// Export-only clip options (trim range, resample fps, keyframe reduction).
    /// Preview ignores them (it passes [`ClipOptions::full`]); export honours them.
    pub options: ClipOptions,
    /// Include the character mesh + skin weights (`true`, the default), or export
    /// the skeleton + animation only (`false` — "Without Skin", for retargeting
    /// onto another mesh). Preview always passes `true`.
    pub skin: bool,
}

/// Export-time shaping of the retargeted clip. `full()` is the identity (the
/// whole clip, original keys), used by preview and unrigged/no-clip exports.
#[derive(Debug, Clone, Copy)]
pub struct ClipOptions {
    /// Keep only `[start, end]` of the clip, as fractions of its duration
    /// (0.0–1.0). The kept span is rebased to start at t=0.
    pub trim_start: f32,
    pub trim_end: f32,
    /// Resample to this many keys per second (0 = keep the original keys).
    pub fps: u32,
    /// Drop rotation keys within this angle (radians) of the interpolation of
    /// their neighbours (0 = keep every key).
    pub keyframe_reduction: f32,
}

impl ClipOptions {
    /// The identity: whole clip, original keys, no reduction.
    pub fn full() -> Self {
        Self {
            trim_start: 0.0,
            trim_end: 1.0,
            fps: 0,
            keyframe_reduction: 0.0,
        }
    }
}

/// Floats per key for a channel; morph weights infer it from the data.
fn key_stride(ch: &m2m_io::glb::Channel) -> usize {
    ch.path
        .stride()
        .unwrap_or_else(|| ch.values.len().checked_div(ch.times.len()).unwrap_or(1))
        .max(1)
}

/// The channel's value at time `t`, interpolated (rotations via glam's
/// shortest-arc nlerp, everything else componentwise-linear), clamped at the
/// ends. Returns `key_stride` floats.
fn sample_key(ch: &m2m_io::glb::Channel, t: f32) -> Vec<f32> {
    let s = key_stride(ch);
    let n = ch.times.len();
    if n == 0 {
        return Vec::new();
    }
    let key = |i: usize| &ch.values[i * s..i * s + s];
    if t <= ch.times[0] {
        return key(0).to_vec();
    }
    if t >= ch.times[n - 1] {
        return key(n - 1).to_vec();
    }
    let hi = ch.times.partition_point(|&x| x <= t).max(1);
    let (i, j) = (hi - 1, hi);
    let (a, b) = (ch.times[i], ch.times[j]);
    let u = if b > a { (t - a) / (b - a) } else { 0.0 };
    let (ka, kb) = (key(i), key(j));
    if matches!(ch.path, m2m_io::glb::Path::Rotation) && s == 4 {
        let qa = glam::Quat::from_xyzw(ka[0], ka[1], ka[2], ka[3]);
        let qb = glam::Quat::from_xyzw(kb[0], kb[1], kb[2], kb[3]);
        let q = qa.lerp(qb, u);
        vec![q.x, q.y, q.z, q.w]
    } else {
        (0..s).map(|c| ka[c] * (1.0 - u) + kb[c] * u).collect()
    }
}

/// Keeps only `[start, end]` seconds of a channel, with clean interpolated
/// boundary keys, and rebases the kept keys so they start at t=0.
fn trim_channel(ch: &m2m_io::glb::Channel, start: f32, end: f32) -> m2m_io::glb::Channel {
    let s = key_stride(ch);
    let mut times = vec![0.0];
    let mut values = sample_key(ch, start);
    for (i, &t) in ch.times.iter().enumerate() {
        if t > start && t < end {
            times.push(t - start);
            values.extend_from_slice(&ch.values[i * s..i * s + s]);
        }
    }
    times.push((end - start).max(0.0));
    values.extend(sample_key(ch, end));
    m2m_io::glb::Channel {
        node: ch.node,
        path: ch.path,
        times,
        values,
    }
}

/// Rebuilds a channel as uniform keys at `fps` per second across `[0, duration]`.
fn resample_channel(ch: &m2m_io::glb::Channel, duration: f32, fps: u32) -> m2m_io::glb::Channel {
    let steps = ((duration * fps as f32).round() as usize).max(1);
    let mut times = Vec::with_capacity(steps + 1);
    let mut values = Vec::new();
    for k in 0..=steps {
        let t = k as f32 / steps as f32 * duration;
        times.push(t);
        values.extend(sample_key(ch, t));
    }
    m2m_io::glb::Channel {
        node: ch.node,
        path: ch.path,
        times,
        values,
    }
}

/// Drops keys the interpolation of their kept neighbours already reproduces
/// within `tol` (radians for rotations, world units otherwise) — a greedy
/// collinear-key simplifier. First and last keys are always kept.
///
/// A key is dropped only when the LINEAR playback that will replace it — the
/// interpolation between the surrounding *kept* keys, exactly what glTF/FBX
/// players do — stays within `tol` of the original at every dropped key. That
/// bounds the real reconstruction error, so a constant-velocity single-axis
/// sweep (whose nlerp playback would otherwise drift) is preserved, not
/// flattened to its endpoints.
// ponytail: O(n²) run growth; clips have tens of keys per bone, so fine.
fn reduce_channel(ch: &m2m_io::glb::Channel, tol: f32) -> m2m_io::glb::Channel {
    let s = key_stride(ch);
    let n = ch.times.len();
    if n <= 2 || tol <= 0.0 {
        return ch.clone();
    }
    let is_rot = matches!(ch.path, m2m_io::glb::Path::Rotation) && s == 4;
    let key = |i: usize| &ch.values[i * s..i * s + s];
    let quat = |i: usize| {
        let k = key(i);
        glam::Quat::from_xyzw(k[0], k[1], k[2], k[3])
    };
    // Error at key `mid` if playback interpolates between keys `a` and `b`.
    let error = |a: usize, b: usize, mid: usize| -> f32 {
        let (ta, tb) = (ch.times[a], ch.times[b]);
        let u = if tb > ta {
            (ch.times[mid] - ta) / (tb - ta)
        } else {
            0.0
        };
        if is_rot {
            quat(a).lerp(quat(b), u).angle_between(quat(mid))
        } else {
            (0..s)
                .map(|c| (key(a)[c] * (1.0 - u) + key(b)[c] * u - key(mid)[c]).abs())
                .fold(0.0, f32::max)
        }
    };

    // Grow a run from the last kept key as far as every interior key it would
    // drop still reconstructs within tol; commit the last key that held.
    let mut keep = vec![0usize];
    let mut anchor = 0;
    let mut end = 1;
    while end < n {
        let fits = (anchor + 1..end).all(|mid| error(anchor, end, mid) <= tol);
        if fits && end < n - 1 {
            end += 1;
        } else if fits {
            keep.push(end); // reached the final key
            break;
        } else {
            keep.push(end - 1);
            anchor = end - 1;
        }
    }
    if *keep.last().unwrap() != n - 1 {
        keep.push(n - 1);
    }

    let mut times = Vec::new();
    let mut values = Vec::new();
    for &i in &keep {
        times.push(ch.times[i]);
        values.extend_from_slice(key(i));
    }
    m2m_io::glb::Channel {
        node: ch.node,
        path: ch.path,
        times,
        values,
    }
}

/// Shapes a retargeted clip for export: trim to a fraction range (rebased to
/// zero), resample to a fixed fps, then thin near-redundant keys. Identity when
/// [`ClipOptions::full`]. Feeds both the glb and fbx exporters.
fn finish_clip(mut clip: m2m_io::glb::Clip, opts: ClipOptions) -> m2m_io::glb::Clip {
    let dur = clip.duration.max(0.0);
    let start = opts.trim_start.clamp(0.0, 1.0) * dur;
    let end = (opts.trim_end.clamp(0.0, 1.0) * dur).max(start);
    let trimming = start > f32::EPSILON || end < dur - f32::EPSILON;
    let new_dur = if trimming { end - start } else { dur };

    for ch in &mut clip.channels {
        if trimming {
            *ch = trim_channel(ch, start, end);
        }
        if opts.fps > 0 {
            *ch = resample_channel(ch, new_dur, opts.fps);
        }
        if opts.keyframe_reduction > 0.0 {
            *ch = reduce_channel(ch, opts.keyframe_reduction);
        }
    }
    clip.duration = new_dur;
    clip
}

#[cfg(test)]
mod clip_options_tests {
    use super::{finish_clip, ClipOptions};
    use m2m_io::glb::{Channel, Clip, Path};

    /// A one-second rotation channel with `keys` evenly spaced keys, rotating
    /// from identity to `end_z` radians about Z (so interior keys are NOT
    /// collinear unless the caller makes them so).
    fn rot_clip(keys: usize, end_z: f32) -> Clip {
        let mut times = Vec::new();
        let mut values = Vec::new();
        for i in 0..keys {
            let u = i as f32 / (keys - 1) as f32;
            times.push(u); // duration 1.0s
            let q = glam::Quat::from_rotation_z(u * end_z);
            values.extend_from_slice(&[q.x, q.y, q.z, q.w]);
        }
        Clip {
            name: "t".into(),
            duration: 1.0,
            channels: vec![Channel {
                node: 0,
                path: Path::Rotation,
                times,
                values,
            }],
        }
    }

    #[test]
    fn full_options_leave_the_clip_untouched() {
        let clip = rot_clip(5, 1.0);
        let out = finish_clip(clip.clone(), ClipOptions::full());
        assert_eq!(out, clip);
    }

    #[test]
    fn trim_keeps_the_middle_and_rebases_to_zero() {
        // Keep [0.25, 0.75] of a 1s clip → 0.5s, starting at t=0.
        let out = finish_clip(
            rot_clip(5, 1.0),
            ClipOptions {
                trim_start: 0.25,
                trim_end: 0.75,
                fps: 0,
                keyframe_reduction: 0.0,
            },
        );
        assert!(
            (out.duration - 0.5).abs() < 1e-5,
            "duration {}",
            out.duration
        );
        let ch = &out.channels[0];
        assert_eq!(*ch.times.first().unwrap(), 0.0);
        assert!((ch.times.last().unwrap() - 0.5).abs() < 1e-5);
        // Interior key at old t=0.5 rebases to 0.25.
        assert!(ch.times.iter().any(|t| (t - 0.25).abs() < 1e-5));
    }

    #[test]
    fn resample_lays_down_uniform_keys_at_the_chosen_fps() {
        // 1s clip at 24fps → 24 intervals → 25 keys.
        let out = finish_clip(
            rot_clip(5, 1.0),
            ClipOptions {
                trim_start: 0.0,
                trim_end: 1.0,
                fps: 24,
                keyframe_reduction: 0.0,
            },
        );
        assert_eq!(out.channels[0].times.len(), 25);
        assert_eq!(out.channels[0].values.len(), 25 * 4);
    }

    #[test]
    fn reduction_drops_redundant_keys_and_stays_within_tolerance() {
        // A motionless track (nine identical keys) collapses to its two ends.
        let still = finish_clip(
            rot_clip(9, 0.0),
            ClipOptions {
                trim_start: 0.0,
                trim_end: 1.0,
                fps: 0,
                keyframe_reduction: 0.05,
            },
        );
        assert_eq!(still.channels[0].times.len(), 2);

        // A real sweep is thinned, but every ORIGINAL key must still be
        // reproduced within tolerance by the reduced track's linear playback —
        // the property that keeps reduction from degrading the motion.
        let tol = 0.05;
        let source = rot_clip(9, 3.0);
        let reduced = finish_clip(
            source.clone(),
            ClipOptions {
                trim_start: 0.0,
                trim_end: 1.0,
                fps: 0,
                keyframe_reduction: tol,
            },
        );
        let rc = &reduced.channels[0];
        assert!(
            rc.times.len() < 9 && rc.times.len() >= 2,
            "len {}",
            rc.times.len()
        );
        let sc = &source.channels[0];
        for i in 0..sc.times.len() {
            let orig = &sc.values[i * 4..i * 4 + 4];
            let played = super::sample_key(rc, sc.times[i]);
            let a = glam::Quat::from_xyzw(orig[0], orig[1], orig[2], orig[3]);
            let b = glam::Quat::from_xyzw(played[0], played[1], played[2], played[3]);
            assert!(
                a.angle_between(b) <= tol + 1e-4,
                "key {i} drifts {}",
                a.angle_between(b)
            );
        }
    }
}

pub fn export_glb(
    model: &[u8],
    skeleton: &FittedSkeleton,
    falloff: f32,
    animation: Option<Animation>,
) -> Result<Vec<u8>, RigError> {
    check_bone_order(skeleton)?;
    let skin = animation.is_none_or(|a| a.skin);

    let clip = match animation {
        Some(a) => Some(finish_clip(
            retarget_clip(
                &m2m_io::glb::read(a.library)?,
                skeleton,
                a.clip,
                a.mirror,
                a.arm_space,
            )?,
            a.options,
        )),
        None => None,
    };

    // "Without Skin": skeleton + animation only, no mesh. Rebuild from an empty
    // mesh (same path for glTF and FBX sources) so there is nothing to skin.
    if !skin {
        let document = rigged_document(
            skeleton,
            &m2m_core::mesh::Mesh::default(),
            &m2m_core::skinning::SkinWeights::default(),
            Vec::new(),
            FbxShading::default(),
            clip.into_iter().collect(),
        );
        return Ok(m2m_io::glb::write(&document)?);
    }

    let (mesh, weights, _) = solve(model, skeleton, falloff)?;

    // Only a glTF source can be augmented in place. An FBX is rebuilt, keeping
    // the normals and UVs the reader carried through (materials/textures are not
    // read from FBX yet).
    if !model.starts_with(b"glTF") {
        let document = rigged_document(
            skeleton,
            &mesh,
            &weights,
            Vec::new(),
            fbx_source_shading(model),
            clip.into_iter().collect(),
        );
        return Ok(m2m_io::glb::write(&document)?);
    }

    let document = m2m_io::glb::read(model)?;
    let mesh_node_world = document
        .primitives
        .iter()
        .find_map(|p| p.node)
        .and_then(|n| document.world_transforms().get(n).copied())
        .unwrap_or(glam::Mat4::IDENTITY);
    let bones = graft_bones(skeleton, mesh_node_world);
    let per_primitive = per_primitive_skins(&document, &weights)?;
    let animation = clip.as_ref().map(graft_animation_of);
    Ok(m2m_io::glb::graft::graft_skin(
        model,
        &bones,
        &per_primitive,
        animation.as_ref(),
    )?)
}

/// The skeleton as grafting bones: local rest transform and inverse bind matrix
/// per bone, composed exactly as [`rigged_document`] does so a grafted export
/// binds identically to a rebuilt one.
///
/// The inverse bind folds in the mesh node's world transform, so a mesh that
/// keeps its original (possibly transformed) node still binds at the rest pose:
/// `jointWorld * IBM = meshNodeWorld` at bind, and for the common identity mesh
/// node this is just `jointWorld⁻¹`.
fn graft_bones(
    skeleton: &FittedSkeleton,
    mesh_node_world: glam::Mat4,
) -> Vec<m2m_io::glb::graft::GraftBone> {
    let position = |index: usize| {
        skeleton
            .positions
            .get(index)
            .map_or(glam::Vec3::ZERO, |p| glam::Vec3::from(*p))
    };
    let world_rotation = world_rotations(skeleton);
    (0..skeleton.bones.len())
        .map(|bone| {
            let parent = skeleton.parents.get(bone).copied().flatten();
            let offset = position(bone) - parent.map_or(glam::Vec3::ZERO, position);
            let local = match parent {
                Some(parent) => world_rotation[parent].inverse() * offset,
                None => offset,
            };
            let inverse_bind =
                (glam::Mat4::from_rotation_translation(world_rotation[bone], position(bone))
                    .inverse()
                    * mesh_node_world)
                    .to_cols_array();
            m2m_io::glb::graft::GraftBone {
                name: skeleton.bones[bone].clone(),
                parent,
                translation: local.to_array(),
                rotation: skeleton
                    .rotations
                    .get(bone)
                    .copied()
                    .unwrap_or([0.0, 0.0, 0.0, 1.0]),
                inverse_bind,
            }
        })
        .collect()
}

/// Slices the merged bind weights back into one skin per primitive, in the
/// primitive order the merged mesh was built in — so the joint/weight arrays
/// land on the vertices they were computed for.
fn per_primitive_skins(
    document: &m2m_io::glb::Document,
    weights: &m2m_core::skinning::SkinWeights,
) -> Result<Vec<m2m_io::glb::graft::GraftPrimitiveSkin>, RigError> {
    let mut out = Vec::new();
    let mut base = 0usize;
    for primitive in &document.primitives {
        let count = primitive.positions.len() / 3;
        let (start, end) = (base * 4, (base + count) * 4);
        let joints = weights
            .indices
            .get(start..end)
            .ok_or(RigError::NothingToBind {
                reason: "the bind produced fewer weights than the mesh has vertices",
            })?
            .to_vec();
        let w = weights
            .weights
            .get(start..end)
            .ok_or(RigError::NothingToBind {
                reason: "the bind produced fewer weights than the mesh has vertices",
            })?
            .to_vec();
        out.push(m2m_io::glb::graft::GraftPrimitiveSkin { joints, weights: w });
        base += count;
    }
    Ok(out)
}

/// A retargeted clip as grafting channels.
fn graft_animation_of(clip: &m2m_io::glb::Clip) -> m2m_io::glb::graft::GraftAnimation {
    m2m_io::glb::graft::GraftAnimation {
        name: clip.name.clone(),
        channels: clip
            .channels
            .iter()
            .map(|c| m2m_io::glb::graft::GraftChannel {
                bone: c.node,
                path: c.path,
                times: c.times.clone(),
                values: c.values.clone(),
            })
            .collect(),
    }
}

