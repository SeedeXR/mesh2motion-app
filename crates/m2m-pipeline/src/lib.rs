    /// The retargeted animation keeps the skeleton together — it does not fling
    /// bones across the scene.
    ///
    /// Regression: the retarget's target translations were the raw world offset
    /// between a bone and its parent, while the exported bone nodes (and the
    /// source rig) express translation in the parent's LOCAL frame. At playback
    /// the parent's rotation was applied to a value already in world space, so
    /// every bone offset was double-rotated and the mesh exploded into shards.
    /// No count catches it — the clip name, channel count and time axis are all
    /// correct — so this composes the first animated frame and checks the bones
    /// stay near the character, not scattered to infinity.
    #[test]
    fn the_animation_does_not_fling_the_skeleton_apart() {
        let skeleton = fit("human", &model("models/model-human.glb")).expect("fits");
        let bytes = super::export_glb(
            &model("models/model-human.glb"),
            &skeleton,
            2.0,
            Some(super::Animation {
                library: &library(),
                clip: "Chest_Open",
                mirror: false,
                arm_space: 50.0,
                options: super::ClipOptions::full(),
                skin: true,
            }),
        )
        .expect("exports");
        let back = m2m_io::glb::read(&bytes).expect("reads back");
        let clip = &back.clips[0];

        // Frame-0 local transform per node: the animation's first key overrides
        // the node's rest translation/rotation.
        let mut translation: Vec<glam::Vec3> = back
            .nodes
            .iter()
            .map(|n| glam::Vec3::from(n.transform.translation))
            .collect();
        let mut rotation: Vec<glam::Quat> = back
            .nodes
            .iter()
            .map(|n| glam::Quat::from_array(n.transform.rotation))
            .collect();
        for channel in &clip.channels {
            match channel.path {
                m2m_io::glb::Path::Translation => {
                    if let Some(t) = channel.values.get(..3) {
                        translation[channel.node] = glam::Vec3::new(t[0], t[1], t[2]);
                    }
                }
                m2m_io::glb::Path::Rotation => {
                    if let Some(q) = channel.values.get(..4) {
                        rotation[channel.node] = glam::Quat::from_xyzw(q[0], q[1], q[2], q[3]);
                    }
                }
                _ => {}
            }
        }

        // Compose world positions down the hierarchy — parents precede children
        // in this document, so one pass suffices.
        let mut world = vec![glam::Mat4::IDENTITY; back.nodes.len()];
        for (node, source) in back.nodes.iter().enumerate() {
            let local = glam::Mat4::from_rotation_translation(rotation[node], translation[node]);
            world[node] = match source.parent {
                Some(parent) => world[parent] * local,
                None => local,
            };
        }

        // The character is ~1.8 m tall; a correctly posed skeleton stays within a
        // couple of metres of the origin. The bug put bones tens of metres out.
        for &joint in &back.skins[0].joints {
            let position = world[joint].transform_point3(glam::Vec3::ZERO);
            assert!(
                position.length() < 5.0,
                "bone node {joint} is {:.1} m from the origin at frame 0 — the skeleton exploded",
                position.length()
            );
        }
    }

    /// Retargeting actually moves the motion; it is not a rename.
    #[test]
    fn the_exported_rotations_are_retargeted_not_copied() {
        // The decisive property, and the one every count misses: a verbatim
        // copy produces the same clip name, the same channel count and the same
        // time axis, while putting limbs up to 180 degrees wrong. Two-sided on
        // purpose — bones whose rest poses AGREE must come through unchanged,
        // so a retarget that mangles everything fails this too.
        let library_document = m2m_io::glb::read(&library()).expect("reads");
        let skeleton = fit("human", &model("models/model-human.glb")).expect("fits");
        let source = super::retarget_source(&library_document).expect("reads the rig");

        let bytes = super::export_glb(
            &model("models/model-human.glb"),
            &skeleton,
            2.0,
            Some(super::Animation {
                library: &library(),
                clip: "Chest_Open",
                mirror: false,
                arm_space: 50.0,
                options: super::ClipOptions::full(),
                skin: true,
            }),
        )
        .expect("exports");
        let read_back = m2m_io::glb::read(&bytes).expect("reads back");
        let out = &read_back.clips[0];

        let chest = library_document
            .clips
            .iter()
            .find(|c| c.name == "Chest_Open")
            .expect("clip");
        let first_source: std::collections::HashMap<usize, glam::Quat> = chest
            .channels
            .iter()
            .filter(|c| c.path == m2m_io::glb::Path::Rotation)
            .filter_map(|c| {
                let bone = *source.bone_of_node.get(&c.node)?;
                let q = c.values.get(..4)?;
                Some((bone, glam::Quat::from_xyzw(q[0], q[1], q[2], q[3])))
            })
            .collect();

        let angle = |a: glam::Quat, b: glam::Quat| {
            let (a, b) = (a.normalize(), b.normalize());
            a.angle_between(if a.dot(b) < 0.0 { -b } else { b })
                .to_degrees()
        };

        // Grafted channels target the bone's NODE; map it back to the bone slot.
        let bone_of_node = |node: usize| read_back.skins[0].joints.iter().position(|&j| j == node);
        let mut moved = 0usize;
        let mut held_where_rest_agrees = 0usize;
        for channel in out
            .channels
            .iter()
            .filter(|c| c.path == m2m_io::glb::Path::Rotation)
        {
            let (Some(bone), Some(q)) = (bone_of_node(channel.node), channel.values.get(..4))
            else {
                continue;
            };
            let Some(before) = first_source.get(&bone) else {
                continue;
            };
            let after = glam::Quat::from_xyzw(q[0], q[1], q[2], q[3]);
            let rest_gap = angle(
                source.rotations.local[bone],
                glam::Quat::from_array(skeleton.rotations[bone]),
            );

            if angle(*before, after) > 1.0 {
                moved += 1;
            } else if rest_gap < 0.01 {
                held_where_rest_agrees += 1;
            }
        }

        // 62 of 66 rest rotations differ, so most bones must have moved.
        assert!(
            moved > 50,
            "only {moved} rotations changed — this is a copy"
        );
        assert!(
            held_where_rest_agrees > 0,
            "every bone moved, including those whose rest poses already agree"
        );
    }

