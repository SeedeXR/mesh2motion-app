    /// A cube of `size`, centred at `at`, as positions and triangle indices.
    fn cube(at: glam::Vec3, size: f32) -> (Vec<f32>, Vec<u32>) {
        let h = size / 2.0;
        let mut positions = Vec::with_capacity(24);
        for corner in 0..8 {
            let sign = |bit: u32| if corner & (1 << bit) == 0 { -h } else { h };
            positions.extend_from_slice(&[at.x + sign(0), at.y + sign(1), at.z + sign(2)]);
        }
        // Two triangles per face, wound consistently enough to voxelise.
        const FACES: [[u32; 4]; 6] = [
            [0, 1, 3, 2],
            [4, 6, 7, 5],
            [0, 4, 5, 1],
            [2, 3, 7, 6],
            [0, 2, 6, 4],
            [1, 5, 7, 3],
        ];
        let mut indices = Vec::with_capacity(36);
        for f in FACES {
            indices.extend_from_slice(&[f[0], f[1], f[2], f[0], f[2], f[3]]);
        }
        (positions, indices)
    }

