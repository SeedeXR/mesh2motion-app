    fn a_template_nobody_ships_is_refused_by_name() {
        let err = fit("chimera", &model("models/model-human.glb")).expect_err("refused");
        assert!(
            matches!(err, super::RigError::UnknownTemplate(name) if name == "chimera"),
            "wrong error"
        );
    }

